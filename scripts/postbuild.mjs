// Runs after `next build`: writes the web manifest, an offline service worker that precaches
// every exported file, and .nojekyll (so GitHub Pages serves the _next folder).
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const OUT = "out";
const base = process.env.NEXT_PUBLIC_BASE_PATH ?? "";

const manifest = {
  name: "مدیریت آرایشگاه",
  short_name: "آرایشگاه",
  lang: "fa",
  dir: "rtl",
  start_url: `${base}/`,
  scope: `${base}/`,
  display: "standalone",
  background_color: "#f5f5f4",
  theme_color: "#b45309",
  icons: [
    { src: `${base}/icons/icon-192.png`, sizes: "192x192", type: "image/png" },
    { src: `${base}/icons/icon-512.png`, sizes: "512x512", type: "image/png" },
  ],
};
writeFileSync(join(OUT, "manifest.webmanifest"), JSON.stringify(manifest, null, 2));
writeFileSync(join(OUT, ".nojekyll"), "");

const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else files.push(full);
  }
};
walk(OUT);

const skip = (rel) => rel === "sw.js" || rel === ".nojekyll" || rel.endsWith(".map");
const urls = [];
const hash = createHash("sha1");
for (const file of files.sort()) {
  const rel = relative(OUT, file).split(sep).join("/");
  if (skip(rel)) continue;
  hash.update(rel).update(readFileSync(file));
  if (rel === "index.html") urls.push(`${base}/`);
  else if (rel.endsWith("/index.html")) urls.push(`${base}/${rel.slice(0, -"index.html".length)}`);
  urls.push(`${base}/${rel}`);
}

const sw = `// Generated by scripts/postbuild.mjs
const CACHE = "barbershop-${hash.digest("hex").slice(0, 12)}";
const URLS = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(URLS)));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then(
      (hit) => hit || fetch(req).catch(() => caches.match(${JSON.stringify(`${base}/`)})),
    ),
  );
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
console.log(`postbuild: ${urls.length} files precached`);
